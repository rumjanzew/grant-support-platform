class Command(BaseCommand):
    help = "Идемпотентно создаёт 30 демонстрационных грантов, не затрагивая другие сущности."

    def add_arguments(self, parser):
        parser.add_argument(
            "--created-by",
            default="admin@example.com",
            help="Email существующего пользователя с ролью Administrator.",
        )
        parser.add_argument(
            "--allow-production",
            action="store_true",
            help="Явно разрешает запуск при DEBUG=False.",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        if not settings.DEBUG and not options["allow_production"]:
            raise CommandError(
                "seed_grants предназначена для demo-данных. "
                "Для осознанного запуска при DEBUG=False добавьте --allow-production."
            )

        administrator = (
            User.objects.select_related("role")
            .filter(
                email__iexact=options["created_by"],
                role__name=Role.Name.ADMINISTRATOR,
                is_active=True,
                deleted_at__isnull=True,
            )
            .first()
        )
        if administrator is None:
            raise CommandError(
                "Не найден активный Administrator с указанным email. "
                "Создайте администратора или передайте --created-by EMAIL."
            )

        today = timezone.localdate()
        created_count = 0
        updated_count = 0

        for index, (title, category, description, amount) in enumerate(
            GRANT_SPECS,
            start=1,
        ):
            if index <= 18:
                status = Grant.Status.OPEN
                start_date = today - timedelta(days=3 + index % 12)
                end_date = today + timedelta(days=20 + index)
            elif index <= 24:
                status = Grant.Status.PUBLISHED
                start_date = today + timedelta(days=3 + index - 18)
                end_date = start_date + timedelta(days=35 + index % 8)
            elif index <= 27:
                status = Grant.Status.CLOSED
                end_date = today - timedelta(days=4 + index - 25)
                start_date = end_date - timedelta(days=40)
            elif index <= 29:
                status = Grant.Status.ARCHIVED
                end_date = today - timedelta(days=90 + index)
                start_date = end_date - timedelta(days=45)
            else:
                status = Grant.Status.DRAFT
                start_date = today + timedelta(days=45)
                end_date = start_date + timedelta(days=50)

            _, was_created = Grant.objects.update_or_create(
                code=f"CATALOG-DEMO-{index:03d}",
                defaults={
                    "title": title,
                    "description": description,
                    "category": category,
                    "start_date": start_date,
                    "end_date": end_date,
                    "max_amount": Decimal(amount),
                    "status": status,
                    "created_by": administrator,
                },
            )
            created_count += int(was_created)
            updated_count += int(not was_created)

        self.stdout.write(self.style.SUCCESS("Демонстрационный каталог грантов готов."))
        self.stdout.write(
            f"Создано: {created_count}; обновлено: {updated_count}; всего: {len(GRANT_SPECS)}."
        )
        self.stdout.write(
            "Статусы: OPEN=18, PUBLISHED=6, CLOSED=3, ARCHIVED=2, DRAFT=1."
        )
